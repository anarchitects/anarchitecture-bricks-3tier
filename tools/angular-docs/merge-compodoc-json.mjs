import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const workspaceRoot = process.cwd();
const sources = [
  {
    project: 'auth-angular',
    file: join(
      workspaceRoot,
      'dist/docs/compodoc/auth-angular/json/documentation.json',
    ),
  },
  {
    project: 'forms-angular',
    file: join(
      workspaceRoot,
      'dist/docs/compodoc/forms-angular/json/documentation.json',
    ),
  },
];

const mergedDir = join(workspaceRoot, 'dist/docs/compodoc/merged');
const mergedFile = join(mergedDir, 'documentation.json');
const storybookCompodocModule = join(
  workspaceRoot,
  'libs/storybook/angular/.storybook/compodoc.ts',
);

function mergeValues(left, right) {
  if (Array.isArray(left) && Array.isArray(right)) {
    return [...left, ...right];
  }

  if (
    left &&
    right &&
    typeof left === 'object' &&
    typeof right === 'object' &&
    !Array.isArray(left) &&
    !Array.isArray(right)
  ) {
    const merged = { ...left };
    for (const [key, value] of Object.entries(right)) {
      if (key in merged) {
        merged[key] = mergeValues(merged[key], value);
      } else {
        merged[key] = value;
      }
    }
    return merged;
  }

  return right;
}

const loaded = sources.map(({ project, file }) => {
  try {
    const content = readFileSync(file, 'utf8');
    return {
      project,
      document: JSON.parse(content),
    };
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(
      `Missing Compodoc JSON for ${project} at ${file}. Run the compodoc targets first.\n${detail}`,
    );
  }
});

let merged = {};
for (const { document } of loaded) {
  merged = mergeValues(merged, document);
}

mkdirSync(mergedDir, { recursive: true });
writeFileSync(mergedFile, `${JSON.stringify(merged, null, 2)}\n`);

const tsModule = `// AUTO-GENERATED by tools/angular-docs/merge-compodoc-json.mjs\nexport const compodocJson = ${JSON.stringify(
  merged,
  null,
  2,
)} as const;\n`;

writeFileSync(storybookCompodocModule, tsModule);

console.log(`Merged Compodoc JSON written to ${mergedFile}`);
console.log(`Storybook Compodoc module updated at ${storybookCompodocModule}`);
